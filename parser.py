# parser.py
# ==================================================
# 資料解析模組
#
# 功能：
# 1. 讀取環境部下載的月平均值 CSV 檔案
# 2. 擷取測站名稱
# 3. 取得 PM2.5 與 PM10 資料
# 4. 過濾無效值與異常值
# 5. 整理成 records 格式回傳
#
# 輸出格式：
#
# [
#     {
#         "site": "基隆",
#         "date": "2025/01",
#         "pm25": 15.6,
#         "pm10": 28.4
#     },
#     ...
# ]
# ==================================================

# CSV 讀取模組
import csv

# 作業系統模組
# 用於檢查檔案是否存在
import os


# ==================================================
# 從標題列取得測站名稱
#
# 範例：
# ["月平均值查詢-基隆"]
#
# 回傳：
# "基隆"
# ==================================================
def _extract_site(header_row):

    # 若 header_row 有資料
    # 取第一個欄位
    # 否則給空字串
    text = header_row[0] if header_row else ""

    # 若標題中包含 "-"
    if "-" in text:

        # split("-")
        # 將字串切開
        #
        # "月平均值查詢-基隆"
        # ->
        # ["月平均值查詢","基隆"]
        #
        # [-1] 取最後一個元素
        return text.split("-")[-1].strip()

    # 若格式不符
    # 回傳預設值
    return "未知測站"


# ==================================================
# 讀取並解析空氣品質檔案
#
# 參數：
# filepath
#
# 回傳：
# records, site
# ==================================================
def parse_air_quality_file(filepath):

    """
    讀取月平均值 CSV

    回傳：

    records：
    [
        {
            "site":"基隆",
            "date":"2025/01",
            "pm25":15.2,
            "pm10":31.5
        }
    ]

    site：
    "基隆"
    """

    # ==============================================
    # 檢查檔案是否存在
    # ==============================================

    # 若找不到檔案
    if not os.path.exists(filepath):

        # 拋出錯誤給 main.py 處理
        raise FileNotFoundError(
            f"找不到檔案：{filepath}"
        )

    # ==============================================
    # 讀取 CSV
    # ==============================================

    # 儲存原始資料列
    raw = []

    # 嘗試不同編碼
    #
    # 環境部資料常見：
    # big5
    # cp950
    # utf-8-sig
    #
    for enc in ["big5", "cp950", "utf-8-sig"]:

        try:

            # 使用指定編碼開啟檔案
            with open(filepath, encoding=enc) as f:

                # csv.reader()
                # 將 CSV 轉成二維串列
                raw = list(csv.reader(f))

            # 成功讀取就離開迴圈
            break

        except UnicodeDecodeError:

            # 編碼錯誤則換下一種編碼
            continue

    # ==============================================
    # 檢查是否成功讀取
    # ==============================================

    if not raw:

        raise ValueError(
            "無法解析檔案編碼"
        )

    # ==============================================
    # 取得測站名稱
    # ==============================================

    # 第一列通常是：
    #
    # 月平均值查詢-基隆
    #
    site = _extract_site(raw[0])

    # ==============================================
    # 建立月份資料字典
    # ==============================================

    # 結構：
    #
    # {
    #   "2025/01":{
    #       "pm25":15.2,
    #       "pm10":30.5
    #   }
    # }
    #
    monthly = {}

    # ==============================================
    # 無效資料集合
    # ==============================================

    invalid = {

        "",     # 空值

        "#",    # 特殊符號

        "*",

        "x",
        "X",

        "-",

        "NR",   # No Record

        "NA",   # Not Available

        "ND"    # Not Detected
    }

    # ==============================================
    # 開始讀取資料列
    # ==============================================

    # 前三列通常是：
    #
    # 第1列：測站名稱
    # 第2列：空白
    # 第3列：欄位名稱
    #
    # 所以從第4列開始
    #
    for row in raw[3:]:

        # 欄位不足
        if len(row) < 3:

            # 跳過
            continue

        # ==========================================
        # 取得欄位資料
        # ==========================================

        # 測項名稱
        item = row[0].strip()

        # 日期
        date = row[1].strip()

        # 數值
        value = row[2].strip()

        # ==========================================
        # 只處理 PM2.5 與 PM10
        # ==========================================

        if item not in ("PM2.5", "PM10"):

            # 例如：
            # SO2
            # NO2
            # CO
            # O3
            #
            # 全部跳過
            continue

        # ==========================================
        # 建立月份資料
        # ==========================================

        # 若尚未建立該月份
        if date not in monthly:

            monthly[date] = {
                "pm25": None,
                "pm10": None
            }

        # ==========================================
        # 檢查是否為無效值
        # ==========================================

        if value in invalid:

            continue

        # ==========================================
        # 轉換成浮點數
        # ==========================================

        try:

            # 例如：
            #
            # "15.6"
            #
            # ->
            #
            # 15.6
            #
            v = float(value)

        except ValueError:

            # 轉換失敗
            continue

        # ==========================================
        # 過濾異常值
        # ==========================================

        # PM2.5 合理範圍
        if item == "PM2.5" and 0 <= v <= 500:

            monthly[date]["pm25"] = v

        # PM10 合理範圍
        elif item == "PM10" and 0 <= v <= 600:

            monthly[date]["pm10"] = v

    # ==============================================
    # 轉換成 records 格式
    # ==============================================

    records = []

    # 日期排序
    #
    # 例如：
    #
    # 2024/01
    # 2024/02
    # 2024/03
    #
    for date in sorted(monthly.keys()):

        # 取得該月份資料
        entry = monthly[date]

        # ==========================================
        # PM2.5 和 PM10 都沒有資料
        # ==========================================

        if (
            entry["pm25"] is None and
            entry["pm10"] is None
        ):

            continue

        # ==========================================
        # 新增到 records
        # ==========================================

        records.append({

            # 測站名稱
            "site": site,

            # 日期
            "date": date,

            # PM2.5
            "pm25": entry["pm25"],

            # PM10
            "pm10": entry["pm10"],
        })

    # ==============================================
    # 顯示解析結果
    # ==============================================

    print(
        f"測站：{site}，"
        f"解析完成：{len(records)} 個月份"
    )

    # ==============================================
    # 回傳結果
    # ==============================================

    return records, site